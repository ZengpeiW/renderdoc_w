#include "FBXExporter.h"
#include <QFile>
#include <QLocale>
#include <QObject>
#include <QTextStream>

namespace
{
QString EscapeFBXString(QString value)
{
  value.replace(QLatin1Char('\\'), QStringLiteral("\\\\"));
  value.replace(QLatin1Char('"'), QStringLiteral("\\\""));
  return value;
}

template <typename T>
void WriteArray(QTextStream &stream, const QString &name, const QVector<T> &values, int indent)
{
  const QString padding(indent, QLatin1Char(' '));
  stream << padding << name << ": *" << values.count() << " {\n";
  stream << padding << "    a: ";

  for(int i = 0; i < values.count(); i++)
  {
    if(i > 0)
      stream << ',';
    stream << values[i];
  }

  stream << "\n" << padding << "}\n";
}

QVector<double> ExpandByPolygonVertex(const QVector<double> &values, int componentCount,
                                      const QVector<qint32> &polygonVertexIndices)
{
  QVector<double> ret;
  ret.reserve(polygonVertexIndices.count() * componentCount);

  for(qint32 encodedIndex : polygonVertexIndices)
  {
    const int index = encodedIndex < 0 ? -encodedIndex - 1 : encodedIndex;
    const int offset = index * componentCount;

    for(int component = 0; component < componentCount; component++)
      ret.push_back(values[offset + component]);
  }

  return ret;
}

QVector<qint32> DecodePolygonVertexIndices(const QVector<qint32> &polygonVertexIndices)
{
  QVector<qint32> ret;
  ret.reserve(polygonVertexIndices.count());

  for(qint32 encodedIndex : polygonVertexIndices)
    ret.push_back(encodedIndex < 0 ? -encodedIndex - 1 : encodedIndex);

  return ret;
}
};    // namespace

bool ExportASCIIFBX(const QString &filename, const FBXMeshData &mesh, QString &error)
{
  const int vertexCount = mesh.positions.count() / 3;

  if(vertexCount == 0 || mesh.positions.count() % 3 != 0)
  {
    error = QObject::tr("The selected mesh has no valid position data.");
    return false;
  }

  if(mesh.polygonVertexIndices.isEmpty())
  {
    error = QObject::tr("The selected mesh has no supported primitives.");
    return false;
  }

  for(qint32 encodedIndex : mesh.polygonVertexIndices)
  {
    const int index = encodedIndex < 0 ? -encodedIndex - 1 : encodedIndex;
    if(index < 0 || index >= vertexCount)
    {
      error = QObject::tr("The generated FBX contains an invalid vertex index.");
      return false;
    }
  }

  QFile file(filename);
  if(!file.open(QIODevice::WriteOnly | QIODevice::Text | QIODevice::Truncate))
  {
    error = QObject::tr("Couldn't open '%1' for writing: %2").arg(filename).arg(file.errorString());
    return false;
  }

  QTextStream stream(&file);
  stream.setLocale(QLocale::c());
  stream.setRealNumberNotation(QTextStream::SmartNotation);
  stream.setRealNumberPrecision(17);

  const QString objectName =
      EscapeFBXString(mesh.name.isEmpty() ? QStringLiteral("RenderDocMesh") : mesh.name);
  const qint64 geometryID = 100000;
  const qint64 modelID = 100001;

  stream << "; FBX 7.4.0 project file\n"
            "; Generated by RenderDoc\n\n"
            "FBXHeaderExtension:  {\n"
            "    FBXHeaderVersion: 1003\n"
            "    FBXVersion: 7400\n"
            "    Creator: \"RenderDoc\"\n"
            "}\n"
            "GlobalSettings:  {\n"
            "    Version: 1000\n"
            "    Properties70:  {\n"
            "        P: \"UpAxis\", \"int\", \"Integer\", \"\",1\n"
            "        P: \"UpAxisSign\", \"int\", \"Integer\", \"\",1\n"
            "        P: \"FrontAxis\", \"int\", \"Integer\", \"\",2\n"
            "        P: \"FrontAxisSign\", \"int\", \"Integer\", \"\",-1\n"
            "        P: \"CoordAxis\", \"int\", \"Integer\", \"\",0\n"
            "        P: \"CoordAxisSign\", \"int\", \"Integer\", \"\",1\n"
            "        P: \"UnitScaleFactor\", \"double\", \"Number\", \"\",1\n"
            "        P: \"OriginalUnitScaleFactor\", \"double\", \"Number\", \"\",1\n"
            "    }\n"
            "}\n"
            "Definitions:  {\n"
            "    Version: 100\n"
            "    Count: 2\n"
            "    ObjectType: \"Geometry\" {\n"
            "        Count: 1\n"
            "    }\n"
            "    ObjectType: \"Model\" {\n"
            "        Count: 1\n"
            "    }\n"
            "}\n"
            "Objects:  {\n";

  stream << "    Geometry: " << geometryID << ", \"Geometry::" << objectName << "\", \"Mesh\" {\n";
  stream << "        GeometryVersion: 124\n";
  WriteArray(stream, QStringLiteral("Vertices"), mesh.positions, 8);
  WriteArray(stream, QStringLiteral("PolygonVertexIndex"), mesh.polygonVertexIndices, 8);

  if(mesh.normals.count() == vertexCount * 3)
  {
    stream << "        LayerElementNormal: 0 {\n"
              "            Version: 101\n"
              "            Name: \"Normal\"\n"
              "            MappingInformationType: \"ByPolygonVertex\"\n"
              "            ReferenceInformationType: \"Direct\"\n";
    WriteArray(stream, QStringLiteral("Normals"),
               ExpandByPolygonVertex(mesh.normals, 3, mesh.polygonVertexIndices), 12);
    stream << "        }\n";
  }

  if(mesh.tangents.count() == vertexCount * 3)
  {
    stream << "        LayerElementTangent: 0 {\n"
              "            Version: 101\n"
              "            Name: \"Tangent\"\n"
              "            MappingInformationType: \"ByPolygonVertex\"\n"
              "            ReferenceInformationType: \"Direct\"\n";
    WriteArray(stream, QStringLiteral("Tangents"),
               ExpandByPolygonVertex(mesh.tangents, 3, mesh.polygonVertexIndices), 12);
    stream << "        }\n";
  }

  if(mesh.colors.count() == vertexCount * 4)
  {
    stream << "        LayerElementColor: 0 {\n"
              "            Version: 101\n"
              "            Name: \"Color\"\n"
              "            MappingInformationType: \"ByPolygonVertex\"\n"
              "            ReferenceInformationType: \"IndexToDirect\"\n";
    WriteArray(stream, QStringLiteral("Colors"), mesh.colors, 12);
    WriteArray(stream, QStringLiteral("ColorIndex"),
               DecodePolygonVertexIndices(mesh.polygonVertexIndices), 12);
    stream << "        }\n";
  }

  for(int uv = 0; uv < mesh.texcoords.count() && uv < 3; uv++)
  {
    if(mesh.texcoords[uv].count() != vertexCount * 2)
      continue;

    stream << "        LayerElementUV: " << uv << " {\n"
           << "            Version: 101\n"
           << "            Name: \"UVChannel_" << (uv + 1) << "\"\n"
           << "            MappingInformationType: \"ByPolygonVertex\"\n"
           << "            ReferenceInformationType: \"IndexToDirect\"\n";
    WriteArray(stream, QStringLiteral("UV"), mesh.texcoords[uv], 12);
    WriteArray(stream, QStringLiteral("UVIndex"),
               DecodePolygonVertexIndices(mesh.polygonVertexIndices), 12);
    stream << "        }\n";
  }

  stream << "        Layer: 0 {\n"
            "            Version: 100\n";

  if(mesh.normals.count() == vertexCount * 3)
    stream << "            LayerElement:  {\n"
              "                Type: \"LayerElementNormal\"\n"
              "                TypedIndex: 0\n"
              "            }\n";
  if(mesh.tangents.count() == vertexCount * 3)
    stream << "            LayerElement:  {\n"
              "                Type: \"LayerElementTangent\"\n"
              "                TypedIndex: 0\n"
              "            }\n";
  if(mesh.colors.count() == vertexCount * 4)
    stream << "            LayerElement:  {\n"
              "                Type: \"LayerElementColor\"\n"
              "                TypedIndex: 0\n"
              "            }\n";
  for(int uv = 0; uv < mesh.texcoords.count() && uv < 3; uv++)
    if(mesh.texcoords[uv].count() == vertexCount * 2)
      stream << "            LayerElement:  {\n"
                "                Type: \"LayerElementUV\"\n"
                "                TypedIndex: "
             << uv << "\n"
             << "            }\n";

  stream << "        }\n"
            "    }\n";

  stream << "    Model: " << modelID << ", \"Model::" << objectName
         << "\", \"Mesh\" {\n"
            "        Version: 232\n"
            "        Properties70:  {\n"
            "            P: \"InheritType\", \"enum\", \"\", \"\",1\n"
            "        }\n"
            "        Shading: T\n"
            "        Culling: \"CullingOff\"\n"
            "    }\n"
            "}\n"
            "Connections:  {\n";
  stream << "    C: \"OO\"," << geometryID << ',' << modelID << "\n";
  stream << "    C: \"OO\"," << modelID
         << ",0\n"
            "}\n";

  file.close();

  if(file.error() != QFileDevice::NoError)
  {
    error = QObject::tr("Failed while writing '%1': %2").arg(filename).arg(file.errorString());
    return false;
  }

  return true;
}
